import argparse
from pathlib import Path
from collections import defaultdict

import yaml
import numpy as np
from PIL import Image, ImageDraw, ImageFont
import cv2


def parse_args():
    parser = argparse.ArgumentParser(
        description="Stitch validation images with mask overlays and compute defect stats."
    )
    parser.add_argument(
        "--data-yaml",
        type=str,
        default="data/processed/stage2/data.yaml",
        help="Path to the data.yaml generated by consolidate.py",
    )
    parser.add_argument(
        "--output-dir",
        type=str,
        default="visualizations/val_stitched",
        help="Directory to save stitched visualizations",
    )
    parser.add_argument(
        "--alpha",
        type=float,
        default=0.45,
        help="Transparency of mask overlay (0.0 - 1.0)",
    )
    parser.add_argument(
        "--font-size",
        type=int,
        default=18,
        help="Font size for annotations on stitched image",
    )
    return parser.parse_args()


def load_yaml(path):
    with open(path, "r") as f:
        return yaml.safe_load(f)


def get_class_colors(num_classes):
    """Generate distinct colors for each class."""
    np.random.seed(42)
    colors = {}
    for i in range(num_classes):
        hue = int(180 * (i / max(num_classes, 1)))
        # HSV to BGR via OpenCV, then to RGB
        hsv = np.uint8([[[hue, 255, 255]]])
        bgr = cv2.cvtColor(hsv, cv2.COLOR_HSV2BGR)[0][0]
        colors[i] = (int(bgr[2]), int(bgr[1]), int(bgr[0]))  # RGB tuple
    return colors


def parse_yolo_label(label_path, img_w, img_h):
    """
    Parse YOLO segmentation label file.
    Returns list of dicts: [{class_idx, polygon[(x,y), ...]}, ...]
    """
    instances = []
    if not label_path.exists():
        return instances

    with open(label_path, "r") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            parts = line.split()
            if len(parts) < 7:  # class + at least 3 points (6 coords)
                continue
            class_idx = int(parts[0])
            coords = list(map(float, parts[1:]))
            polygon = []
            for i in range(0, len(coords), 2):
                x = int(coords[i] * img_w)
                y = int(coords[i + 1] * img_h)
                polygon.append((x, y))
            instances.append({"class_idx": class_idx, "polygon": polygon})
    return instances


def create_overlay(image, instances, class_colors, alpha=0.45):
    """
    Draw segmentation masks on a copy of the image.
    Returns (overlay_image, mask_stats).
    mask_stats: {class_idx: pixel_count}
    """
    img_array = np.array(image)
    overlay = img_array.copy()
    mask = np.zeros(img_array.shape[:2], dtype=np.uint8)
    mask_stats = defaultdict(int)

    for inst in instances:
        cls = inst["class_idx"]
        poly = inst["polygon"]
        color = class_colors.get(cls, (255, 0, 0))

        # Draw filled polygon on overlay
        pts = np.array([poly], dtype=np.int32)
        cv2.fillPoly(overlay, pts, color)

        # Update binary mask for pixel counting
        temp_mask = np.zeros(img_array.shape[:2], dtype=np.uint8)
        cv2.fillPoly(temp_mask, pts, 1)
        mask |= temp_mask
        mask_stats[cls] += int(temp_mask.sum())

    # Blend original and overlay
    blended = cv2.addWeighted(overlay, alpha, img_array, 1 - alpha, 0)

    # Total defect pixels (union of all masks)
    total_defect_pixels = int(mask.sum())

    return blended, total_defect_pixels, dict(mask_stats)


def stitch_images(
    left_img,
    right_img,
    title_left="ORIGINAL",
    title_right="MASK OVERLAY",
    font_size=18,
    class_names=None,
    mask_stats=None,
    total_defect_px=0,
    total_pixels=1,
):
    """
    Stitch two PIL Images side-by-side with titles and a bottom stats bar.
    """
    w1, h1 = left_img.size
    w2, h2 = right_img.size

    # Ensure same height
    target_h = max(h1, h2)
    if h1 != target_h:
        left_img = left_img.resize((int(w1 * target_h / h1), target_h), Image.LANCZOS)
    if h2 != target_h:
        right_img = right_img.resize((int(w2 * target_h / h2), target_h), Image.LANCZOS)

    w1, h1 = left_img.size
    w2, h2 = right_img.size

    # Stats bar height
    stats_h = 140 if mask_stats else 60
    canvas_w = w1 + w2
    canvas_h = target_h + 40 + stats_h  # 40 for titles

    canvas = Image.new("RGB", (canvas_w, canvas_h), (30, 30, 30))
    draw = ImageDraw.Draw(canvas)

    # Try to load a font, fall back to default
    try:
        font_title = ImageFont.truetype(
            "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf", font_size + 4
        )
        font_text = ImageFont.truetype(
            "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf", font_size
        )
        font_small = ImageFont.truetype(
            "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf", font_size - 2
        )
    except Exception:
        font_title = ImageFont.load_default()
        font_text = ImageFont.load_default()
        font_small = ImageFont.load_default()

    # Paste images
    canvas.paste(left_img, (0, 40))
    canvas.paste(right_img, (w1, 40))

    # Titles
    draw.text((w1 // 2 - 60, 10), title_left, fill=(200, 200, 200), font=font_title)
    draw.text(
        (w1 + w2 // 2 - 70, 10), title_right, fill=(200, 200, 200), font=font_title
    )

    # Divider line
    draw.line([(w1, 0), (w1, canvas_h)], fill=(80, 80, 80), width=2)

    # Stats section
    bg_pct = 100.0 * (total_pixels - total_defect_px) / total_pixels
    defect_pct = 100.0 * total_defect_px / total_pixels

    y_off = target_h + 50
    draw.text(
        (20, y_off),
        f"BACKGROUND: {bg_pct:.2f}%  |  DEFECT: {defect_pct:.2f}%  ({total_defect_px:,} / {total_pixels:,} px)",
        fill=(255, 255, 255),
        font=font_text,
    )

    if mask_stats and class_names:
        y_off += 30
        draw.text(
            (20, y_off),
            "Defect breakdown by class:",
            fill=(180, 180, 180),
            font=font_small,
        )
        y_off += 22
        x_off = 20
        for cls_idx, px_count in sorted(mask_stats.items()):
            cls_name = class_names.get(cls_idx, f"class_{cls_idx}")
            cls_pct = 100.0 * px_count / total_pixels
            text = f"  {cls_name}: {cls_pct:.2f}% ({px_count:,} px)"
            draw.text((x_off, y_off), text, fill=(200, 200, 200), font=font_small)
            y_off += 20

    return canvas


def main():
    args = parse_args()

    print("=" * 60)
    print("   VALIDATION SET VISUALIZER & DEFECT ANALYZER")
    print("=" * 60)

    # Load data.yaml
    config = load_yaml(args.data_yaml)
    base_path = Path(config.get("path", Path(args.data_yaml).parent))
    val_img_dir = base_path / config.get("val", "val/images")
    # Labels are assumed to be in val/labels parallel to val/images
    val_lbl_dir = val_img_dir.parent / "labels"

    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    # Class names from data.yaml
    names_dict = config.get("names", {})
    class_names = {int(k): v for k, v in names_dict.items()}
    num_classes = len(class_names)
    class_colors = get_class_colors(num_classes)

    image_files = sorted(
        [
            p
            for p in val_img_dir.iterdir()
            if p.suffix.lower() in (".jpg", ".jpeg", ".png", ".bmp", ".webp")
        ]
    )

    if not image_files:
        print(f"[!] No images found in {val_img_dir}")
        return

    print(f"[+] Found {len(image_files)} validation images.")
    print(f"[+] Output directory: {output_dir.resolve()}")
    print(f"[+] Classes: {class_names}")
    print("[+] Processing...\n")

    global_defect_pixels = 0
    global_total_pixels = 0
    processed = 0

    for img_path in image_files:
        # Corresponding label file
        lbl_path = val_lbl_dir / (img_path.stem + ".txt")

        # Load image
        image = Image.open(img_path).convert("RGB")
        img_w, img_h = image.size
        total_pixels = img_w * img_h

        # Parse labels
        instances = parse_yolo_label(lbl_path, img_w, img_h)

        if not instances:
            # No labels: show original + empty overlay (just original again)
            overlay_img = np.array(image)
            total_defect_px = 0
            mask_stats = {}
        else:
            overlay_img, total_defect_px, mask_stats = create_overlay(
                image, instances, class_colors, alpha=args.alpha
            )
            overlay_img = Image.fromarray(overlay_img)

        # Stitch
        stitched = stitch_images(
            image,
            overlay_img if instances else image,
            title_left="ORIGINAL",
            title_right="MASK OVERLAY" if instances else "NO LABELS",
            font_size=args.font_size,
            class_names=class_names,
            mask_stats=mask_stats if instances else None,
            total_defect_px=total_defect_px,
            total_pixels=total_pixels,
        )

        # Save
        out_path = output_dir / f"{img_path.stem}_stitched.jpg"
        stitched.save(out_path, quality=95)

        global_defect_pixels += total_defect_px
        global_total_pixels += total_pixels
        processed += 1

        if processed % 50 == 0 or processed == len(image_files):
            print(f"    -> Processed {processed}/{len(image_files)} images...")

    # Global summary
    print("\n" + "=" * 60)
    print("   GLOBAL VALIDATION SET STATISTICS")
    print("=" * 60)
    if global_total_pixels > 0:
        g_bg = (
            100.0 * (global_total_pixels - global_defect_pixels) / global_total_pixels
        )
        g_df = 100.0 * global_defect_pixels / global_total_pixels
        print(f"Total Images Processed : {processed}")
        print(f"Total Pixels Analyzed  : {global_total_pixels:,}")
        print(f"Background             : {g_bg:.4f}%")
        print(f"Defect (all classes)   : {g_df:.4f}%  ({global_defect_pixels:,} px)")
    print(f"\n[✓] All stitched images saved to: {output_dir.resolve()}")
    print("=" * 60)


if __name__ == "__main__":
    main()
